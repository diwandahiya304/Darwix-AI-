"""Renders the 4 required scripted scenarios to real stereo WAV files and
derives live_nudges/tests/ground_truth.yaml from the actual rendered
timing (see sim/scenarios.py's GROUND_TRUTH_SPEC for which utterance
triggers which expected nudge, and audio_gen/scenarios_audio.py for how
timing is computed).

Run: `make q4-generate-audio` (only needs re-running if
sim/scenarios.py's scripts change — the WAVs and ground truth are
checked into git like any other test fixture).
"""

from __future__ import annotations

import sys

import soundfile as sf
import yaml

from live_nudges.app.settings import REPO_ROOT
from live_nudges.audio_gen.scenarios_audio import build_scenario_audio
from live_nudges.sim.scenarios import GROUND_TRUTH_SPEC, SCENARIOS

AUDIO_DIR = REPO_ROOT / "recordings" / "live_nudges" / "audio"
GROUND_TRUTH_PATH = REPO_ROOT / "live_nudges" / "tests" / "ground_truth.yaml"


def main() -> int:
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    ground_truth: dict = {}

    for scenario in SCENARIOS:
        print(f"Rendering {scenario.scenario_id} ({len(scenario.utterances)} lines)...")
        stereo, sr, timings = build_scenario_audio(scenario)
        wav_path = AUDIO_DIR / f"{scenario.scenario_id}.wav"
        sf.write(str(wav_path), stereo, sr)
        duration_ms = int(len(stereo) / sr * 1000)
        print(f"  wrote {wav_path} ({duration_ms}ms, {len(stereo)} samples @ {sr}Hz)")

        spec = GROUND_TRUTH_SPEC[scenario.scenario_id]
        expected_nudges = []
        for item in spec["expected"]:
            trigger = timings[item["trigger_index"]]
            expected_nudges.append({
                "signal_type": item["signal_type"],
                "topic": item["topic"],
                "expected_after_ms": trigger["end_ms"] + item["after_ms"],
                "expected_before_ms": trigger["end_ms"] + item["before_ms"],
                "note": item["note"],
            })

        ground_truth[scenario.scenario_id] = {
            "scenario_id": scenario.scenario_id,
            "call_duration_ms": duration_ms,
            "expected_nudges": expected_nudges,
            "max_acceptable_nudges": spec["max_acceptable_nudges"],
        }

    GROUND_TRUTH_PATH.write_text(
        "# Auto-generated by live_nudges/scripts/generate_audio.py from the\n"
        "# actual rendered audio timing — do not hand-edit; edit\n"
        "# sim/scenarios.py's GROUND_TRUTH_SPEC and re-run make q4-generate-audio.\n"
        + yaml.safe_dump(ground_truth, sort_keys=False, default_flow_style=False),
        encoding="utf-8",
    )
    print(f"Wrote {GROUND_TRUTH_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
