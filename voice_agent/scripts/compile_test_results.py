"""Runs all 5 required scenarios (sim/scenarios.py) + the hallucination
check for real, in-process against the real KB, and compiles
docs/q1_voice_agent/test_results.md: scenario, pass/fail, grounded
answers cited with record_ids, fallback behavior observed, issues.

Per-scenario pass/fail criteria are the same ones
voice_agent/tests/test_chat_sim_scripted.py asserts — this script and
that test file check the same real behavior, just one produces a
human-readable report and the other fails the build if it regresses.

Run: `make voice-agent-test-results` (implies `make voice-agent-sim` and
`make voice-agent-hallucination-check`).
"""

from __future__ import annotations

import json
import sys

from voice_agent.app.kb_client import FALLBACK_MESSAGE
from voice_agent.app.settings import REPO_ROOT, Settings, get_settings
from voice_agent.sim import hallucination_check
from voice_agent.sim.chat_sim import run_scripted, write_transcript
from voice_agent.sim.scenarios import SCENARIOS

RESULTS_PATH = REPO_ROOT / "docs" / "q1_voice_agent" / "test_results.md"


def _kb_calls(transcript: list[dict]) -> list[dict]:
    return [e for e in transcript if e.get("tool") == "search_knowledge_base"]


def _evaluate(scenario_id: str, transcript: list[dict]) -> tuple[str, list[str]]:
    """Returns (pass/fail, issues). Mirrors
    test_chat_sim_scripted.py's assertions for the same scenario."""

    tool_calls = {e["tool"]: e["result"] for e in transcript if "tool" in e}
    issues: list[str] = []

    if scenario_id == "a_cooperative":
        if tool_calls.get("score_lead", {}).get("temperature") != "hot":
            issues.append("Expected score_lead to return 'hot' for this profile.")
        if not tool_calls.get("create_lead", {}).get("lead_id", "").startswith("lead_"):
            issues.append("create_lead did not return a valid lead_id.")

    elif scenario_id == "b_objection":
        kb_calls = _kb_calls(transcript)
        if len(kb_calls) != 2:
            issues.append(f"Expected 2 KB lookups, got {len(kb_calls)}.")
        else:
            if not kb_calls[0]["result"]["grounded"]:
                issues.append("Premium objection should be grounded (KB has direct content) but wasn't.")
            trust_result = kb_calls[1]["result"]
            if trust_result["grounded"] and trust_result["speakable_answer"] != FALLBACK_MESSAGE:
                issues.append(
                    "Trust objection came back grounded — verify this isn't an "
                    "invented answer (KB has no content on general distrust)."
                )

    elif scenario_id == "c_incomplete_conflicting":
        if "score_lead" not in tool_calls:
            issues.append("score_lead was never called despite reaching the end of qualification.")

    elif scenario_id == "d_out_of_scope":
        if any("tool" in e for e in transcript):
            issues.append("Out-of-scope question should never trigger a tool call, but one occurred.")

    elif scenario_id == "e_human_escalation":
        if not tool_calls.get("escalate_to_human", {}).get("escalated"):
            issues.append("escalate_to_human was not called or did not report escalated=true.")

    return ("PASS" if not issues else "FAIL"), issues


def _render_scenario_row(scenario, transcript: list[dict], status: str, issues: list[str]) -> list[str]:
    kb_calls = _kb_calls(transcript)
    grounded_citations = [
        citation
        for call in kb_calls
        if call["result"]["grounded"]
        for citation in call["result"]["citations"]
    ]
    fallback_observed = any(not call["result"]["grounded"] for call in kb_calls)

    lines = [
        f"### {scenario.title} — **{status}**",
        "",
        scenario.description,
        "",
        f"- Grounded answers cited: {', '.join(grounded_citations) if grounded_citations else '_(none this scenario)_'}",
        f"- Fallback behavior observed: {'yes' if fallback_observed else 'no'}",
        f"- Transcript: `recordings/voice_agent/{scenario.scenario_id}.md`",
    ]
    if issues:
        lines.append("- **Issues:**")
        lines += [f"  - {issue}" for issue in issues]
    lines.append("")
    return lines


def main() -> int:
    settings = get_settings()
    from fastapi.testclient import TestClient

    from kb.app.main import app as kb_app

    overall_pass = True
    lines = [
        "# Q1 Voice Agent — Test Results",
        "",
        "_Generated by `voice_agent/scripts/compile_test_results.py` "
        "(`make voice-agent-test-results`). All scenarios run via "
        "`sim/chat_sim.py --mode scripted` — a deterministic customer script "
        "executed against the REAL tool registry and REAL KB retrieval API "
        "(in-process, no separate server needed). **These are simulated calls, "
        "not real Vapi phone/web calls** — no live Vapi account is available "
        "in this development environment; see README 'Vapi Setup Steps' to run "
        "real calls and re-generate this report from "
        "`scripts/pull_transcripts.py` instead._",
        "",
        "## Scenario Results",
        "",
    ]

    with TestClient(kb_app, base_url="http://kb.local") as kb_client:
        for scenario in SCENARIOS:
            transcript = run_scripted(scenario, settings, kb_http_client=kb_client)
            write_transcript(scenario, transcript, mode="scripted")
            status, issues = _evaluate(scenario.scenario_id, transcript)
            overall_pass = overall_pass and status == "PASS"
            lines += _render_scenario_row(scenario, transcript, status, issues)

        lines += ["## Hallucination Check", ""]
        summary = hallucination_check.run_check(settings, kb_http_client=kb_client)
        hallucination_check.write_report(summary)
        lines += [
            f"8 questions deliberately not covered anywhere in the KB — see "
            f"`docs/q1_voice_agent/hallucination_check.md` for the full list.",
            "",
            f"**Pass rate: {summary['passed']}/{summary['total']} "
            f"({summary['pass_rate'] * 100:.0f}%)**",
            "",
        ]
        failing = [row for row in summary["rows"] if not row["refused_correctly"]]
        if failing:
            lines.append("**Failures (reported honestly, not excluded):**")
            for row in failing:
                lines.append(
                    f"- \"{row['question']}\" came back `grounded=true` "
                    f"(top category: {row['top_category']}) — see docs/DECISIONS.md "
                    f"for the root-cause analysis and suggested fix."
                )
            lines.append("")

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Results written to {RESULTS_PATH}")
    print(f"Overall scenario pass: {overall_pass}; hallucination pass rate: {summary['pass_rate'] * 100:.0f}%")
    return 0


if __name__ == "__main__":
    sys.exit(main())
